"""AGRIWISE dashboard server: serves the web pages, nothing else (no database, no calculation).

The pages talk directly to the backend API (port 8000) and to the photo analyzer (port 8100).

    python server.py                              # http://localhost:8080
    python server.py --port 8080 --backend http://192.168.1.20:8000 --vision http://192.168.1.20:8100

By default the backend and the analyzer are looked for on the SAME machine as the page, ports 8000 and
8100: opening http://<pc-ip>:8080 from a phone on the same Wi-Fi then works with no setting.
Only the Python standard library is used.
"""
from __future__ import annotations

import argparse
import json
import os
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

WEB = Path(__file__).resolve().parent / "web"


def config_js(backend: str, vision: str) -> bytes:
    cfg = {"backend": backend.rstrip("/"), "vision": vision.rstrip("/")}
    return ("// generated by server.py\nwindow.AGRIWISE_CONFIG = " + json.dumps(cfg) + ";\n").encode()


class Handler(SimpleHTTPRequestHandler):
    backend = ""
    vision = ""

    def do_GET(self):  # noqa: N802
        if self.path.split("?")[0] == "/config.js":
            body = config_js(self.backend, self.vision)
            self.send_response(200)
            self.send_header("Content-Type", "application/javascript; charset=utf-8")
            self.send_header("Cache-Control", "no-store")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            return
        return super().do_GET()

    def end_headers(self):
        if self.path.endswith((".html", ".js", ".css", "/")):
            self.send_header("Cache-Control", "no-cache")      # always the latest version of the pages
        super().end_headers()

    def log_message(self, fmt, *args):                          # quiet: only errors
        if args and str(args[1] if len(args) > 1 else "").startswith(("4", "5")):
            super().log_message(fmt, *args)


def make_server(port: int, backend: str = "", vision: str = "", host: str = "0.0.0.0") -> ThreadingHTTPServer:
    handler = type("H", (Handler,), {"backend": backend, "vision": vision})
    return ThreadingHTTPServer((host, port), partial(handler, directory=str(WEB)))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--port", type=int, default=int(os.environ.get("DASHBOARD_PORT", 8080)))
    ap.add_argument("--host", default=os.environ.get("DASHBOARD_HOST", "0.0.0.0"))
    ap.add_argument("--backend", default=os.environ.get("BACKEND_URL", ""),
                    help="backend URL as seen from the browser (default: same machine, port 8000)")
    ap.add_argument("--vision", default=os.environ.get("VISION_URL", ""),
                    help="analyzer URL as seen from the browser (default: same machine, port 8100)")
    args = ap.parse_args()
    srv, port = None, args.port
    # Windows can reserve some ports (Hyper-V, WSL, Docker, VirtualBox): WinError 10013 / 10048.
    # Then try the next ones instead of stopping.
    for port in [args.port] + [p for p in (3000, 5500, 8090, 8888, 9080) if p != args.port]:
        try:
            srv = make_server(port, args.backend, args.vision, args.host)
            break
        except OSError as exc:
            print(f"Port {port} unavailable ({exc.strerror or exc}); trying another one...")
    if srv is None:
        raise SystemExit("No free port found: run  python server.py --port <number>")
    print(f"AGRIWISE dashboard: http://localhost:{port}  (Ctrl+C to stop)")
    print(f"  backend : {args.backend or 'same machine, port 8000'}")
    print(f"  analyzer: {args.vision or 'same machine, port 8100'}")
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
